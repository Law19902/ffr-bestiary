"""Write data/worldmap_data.lua (shipped) from extracted/worldmap/worldmap_positions.json (built by
extracted/worldmap/build_worldmap.py from the game's map tables; see its NOTES.md).

The world map is drawn at runtime from the game's own tiles (/Game/UI/Textures/MapCapture/Wld/Wld_N), so the file
holds positions only: map coordinates u, v in 0..1 over the whole world (u across, v down).
  tiles  list of {tex, rect = {u0, v0, u1, v1}, z, island (eMapIslandType number), cond = {op, progress} or nil}
         cond compares the save's main story progress (Progress.Progress[0]); some islands change with the story
  areas  area key -> {u, v} (marker); island areas also get rect = {u0, v0, u1, v1}; areas with no place of their
         own that are on a known island get their island's position (approx = true)
  aspect width / height of the world map frame
"""
import json, os, re

ROOT = os.path.join(os.path.dirname(__file__), '..')
src = json.load(open(os.path.join(ROOT, 'extracted/worldmap/worldmap_positions.json'), encoding='utf8'))
ISLAND = {'Grandshelt': 1, 'Lanzelt': 2, 'Kolobos': 3, 'Dirnado': 4, 'Olderion': 5, 'Zoldaad': 6,
          'MagiNationMysidia': 7, 'Gronoa': 8, 'Pharm': 9, 'LandOfTheCrystals': 10, 'Ardra': 11}   # eMapIslandType


def lua(v):
    if v is None: return 'nil'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(round(v, 6)) if isinstance(v, float) else str(v)
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, list): return '{' + ', '.join(lua(x) for x in v) + '}'
    return '{' + ', '.join('[%s] = %s' % (json.dumps(k), lua(x)) for k, x in v.items()) + '}'


tiles = []
for tid, t in sorted(src['tiles'].items(), key=lambda kv: int(kv[0])):
    cond = None
    if t['visibleCondition']:
        m = re.fullmatch(r'\{progress:0\}(<|>=|==)(\d+)', t['visibleCondition'])
        assert m, t['visibleCondition']
        cond = {'op': m.group(1), 'progress': int(m.group(2))}
    tiles.append({'tex': t['texture'], 'rect': t['texRectUV'], 'z': t['displayPriority'],
                  'island': ISLAND[t['island']], 'cond': cond})

areas = {}
for key, a in src['areas'].items():
    e = {'u': a['u'], 'v': a['v']}
    if key.startswith('island:') and a.get('rectUV'): e['rect'] = a['rectUV']
    areas[key] = e
# Kingdom of Grandshelt spans three islands (Grandshelt, Grandport, Kolobos): the mean of its places fell on the
# bridge between Grandshelt and Grandport, which reads as the sea (25 Oct). Its marker goes on its capital instead.
CAPITAL = {'island:MAP_NAME_001': 'name:MAP_NAME_012'}   # Grandshelt, the Royal Capital
for key, cap in CAPITAL.items():
    areas[key]['u'], areas[key]['v'] = areas[cap]['u'], areas[cap]['v']
# an island's position only for places that are on that island (the Zoldaad railway); not for the airship (no fixed
# place: it showed a marker in the sea) or Fina's Psyche (a dream)
ON_ISLAND = {'name:MAP_NAME_042', 'name:MAP_NAME_082'}   # Timber Tracks, Phantom Train
for key, m in src['missing'].items():
    if key in ON_ISLAND and m.get('fallbackUV'):
        areas[key] = {'u': m['fallbackUV'][0], 'v': m['fallbackUV'][1], 'approx': True}

f = src['frame']['landWholeSize']
out = '-- generated by tools/export_worldmap.py; do not edit\nreturn ' + lua(
    {'aspect': f[0] / f[1], 'tiles': tiles, 'areas': areas}) + '\n'
open(os.path.join(ROOT, 'data/worldmap_data.lua'), 'w', encoding='utf8', newline='\n').write(out)
print('tiles', len(tiles), 'areas', len(areas), 'bytes', len(out))
